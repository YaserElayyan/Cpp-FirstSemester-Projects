#include <iostream>
using namespace std;
int main()
{
	int month;
	cout << "Please Enter a Number to know the month" << endl;
	cin >> month;
	{
		if (month == 1)
			cout << "January" << endl;

		if (month == 2)
			cout << "Febraury" << endl;

		if (month == 3)
			cout << "March" << endl;

		if (month == 4)
			cout << "April" << endl;
		if (month == 5)
			cout << "May" << endl;

		if (month == 6)
			cout << "June" << endl;
		}
	return 0;
}